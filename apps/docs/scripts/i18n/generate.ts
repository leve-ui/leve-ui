/**
 * Generates the routes of every locale other than English (adr/0033).
 *
 * src/routes/en is the only hand-written source. For each other locale, this
 * mirrors it into src/routes/<locale> (git-ignored):
 *
 * - `.mdx` pages are copied. Missing translations fall back to English
 *   (translation from the memory in i18n/<locale>.json is added in #99).
 * - Other route modules (`layout.tsx`, `index.tsx`) re-export the English module.
 *
 * Run: node scripts/i18n/generate.ts (part of `dev`, `build` and `typecheck`)
 */
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES, SOURCE_LOCALE } from '../../src/i18n/locales.ts';

const routes = resolve(dirname(fileURLToPath(import.meta.url)), '../../src/routes');
const source = join(routes, SOURCE_LOCALE);

const HEADER = '// Generated by scripts/i18n/generate.ts from src/routes/en. Do not edit.\n';

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

for (const locale of LOCALES) {
  if (locale === SOURCE_LOCALE) continue;
  const target = join(routes, locale);
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  // Keeps the generated routes out of git (and Biome, which reads .gitignore)
  writeFileSync(join(target, '.gitignore'), '*\n');

  for (const file of walk(source)) {
    const out = join(target, relative(source, file));
    mkdirSync(dirname(out), { recursive: true });
    const ext = extname(file);

    if (ext === '.mdx' || ext === '.md') {
      cpSync(file, out);
    } else if (ext === '.tsx' || ext === '.ts') {
      const from = relative(dirname(out), file).slice(0, -ext.length).replaceAll('\\', '/');
      writeFileSync(out, `${HEADER}export * from '${from}';\nexport { default } from '${from}';\n`);
    } else {
      cpSync(file, out);
    }
  }
  console.log(`i18n: generated src/routes/${locale}`);
}

/**
 * Generates the routes of every locale other than English (adr/0033).
 *
 * src/routes/en is the only hand-written source. For each other locale, this
 * mirrors it into src/routes/<locale> (git-ignored):
 *
 * - `.mdx` pages are translated segment by segment from the translation memory
 *   (i18n/<locale>.json). Segments without a translation stay in English.
 * - Other route modules (`layout.tsx`, `index.tsx`) re-export the English module.
 * - UI strings and props descriptions are written to src/generated/i18n/<locale>.json
 *   (`{ english: translation }`), read by src/i18n/translate.ts.
 *
 * Run: node scripts/i18n/generate.ts (part of `dev`, `build` and `typecheck`)
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { LOCALES, SOURCE_LOCALE } from '../../src/i18n/locales.ts';
import { lookup, ROUTES_DIR, readMemory, SOURCE_DIR, SRC_DIR, walkFiles } from './memory.ts';
import { translateMdx } from './segments.ts';
import { propDescriptions, textSegment, uiStrings } from './ui.ts';

const MESSAGES_DIR = join(SRC_DIR, 'generated/i18n');
rmSync(MESSAGES_DIR, { recursive: true, force: true });
mkdirSync(MESSAGES_DIR, { recursive: true });
const texts = [...uiStrings(SRC_DIR), ...propDescriptions(SRC_DIR)];

const HEADER = '// Generated by scripts/i18n/generate.ts from src/routes/en. Do not edit.\n';

for (const locale of LOCALES) {
  if (locale === SOURCE_LOCALE) continue;
  const target = join(ROUTES_DIR, locale);
  const translate = lookup(readMemory(locale));
  let translated = 0;
  let total = 0;

  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  // Keeps the generated routes out of git (and Biome, which reads .gitignore)
  writeFileSync(join(target, '.gitignore'), '*\n');

  for (const file of walkFiles(SOURCE_DIR)) {
    const path = relative(SOURCE_DIR, file);
    const out = join(target, path);
    mkdirSync(dirname(out), { recursive: true });
    const ext = extname(file);

    if (ext === '.mdx') {
      try {
        const result = translateMdx(readFileSync(file, 'utf8'), translate);
        writeFileSync(out, result.mdx);
        translated += result.translated;
        total += result.total;
      } catch (error) {
        throw new Error(`i18n: cannot generate ${locale}/${path}`, { cause: error });
      }
    } else if (ext === '.tsx' || ext === '.ts') {
      const from = relative(dirname(out), file).slice(0, -ext.length).replaceAll('\\', '/');
      writeFileSync(out, `${HEADER}export * from '${from}';\nexport { default } from '${from}';\n`);
    } else {
      cpSync(file, out);
    }
  }

  const messages: Record<string, string> = {};
  for (const text of texts) {
    const segment = textSegment(text);
    const translation = translate(segment.text);
    if (translation !== undefined) messages[text] = segment.restore(translation);
  }
  writeFileSync(join(MESSAGES_DIR, `${locale}.json`), `${JSON.stringify(messages, null, 2)}\n`);

  console.log(
    `i18n: generated src/routes/${locale} (${translated}/${total} segments translated)` +
      ` and src/generated/i18n/${locale}.json (${Object.keys(messages).length}/${texts.length} strings)`,
  );
}
